const dayMs = 86_400_000;

function articleFor(index: number, supplierId: string): string {
  const prefix = supplierId.replace('sup-', '').slice(0, 3).toUpperCase();
  return `${prefix}-${String(1000 + index * 7).slice(0, 4)}`;
}

function baseSpecs(seed: Seed): Spec[] {
  const rows: Spec[] = [];
  rows.push({ label: 'Фасовка', value: seed.pack });
  if (seed.country) rows.push({ label: 'Страна', value: seed.country });
  rows.push({ label: 'Бренд', value: seed.brand });
  rows.push({ label: 'Температурный режим', value: tempModeLabel(seed.temp) });
  return rows;
}

export function tempModeLabel(mode: TempMode): string {
  switch (mode) {
    case 'frozen':
      return 'Заморозка (−18 °C)';
    case 'chilled':
      return 'Охлаждённый (0…+6 °C)';
    case 'dry':
      return 'Сухой склад (+15…+25 °C)';
  }
}

export const products: Product[] = seeds.map((seed, index) => {
  const categoryId = seed.sub.split('-')[0];
  return {
    id: `p-${String(index + 1).padStart(3, '0')}`,
    supplierId: seed.s,
    categoryId,
    subcategoryId: seed.sub,
    name: seed.n,
    article: articleFor(index, seed.s),
    brand: seed.brand,
    country: seed.country ?? 'Россия',
    unit: seed.unit,
    packSize: seed.pack,
    price: seed.price,
    oldPrice: seed.old,
    stock: seed.stock,
    minQty: seed.min ?? 1,
    step: seed.step ?? 1,
    tempMode: seed.temp,
    tags: seed.tags ?? [],
    description: seed.desc,
    specs: [...baseSpecs(seed), ...(seed.specs ?? []).map(([label, value]) => ({ label, value }))],
    isActive: true,
    createdAt: new Date(Date.now() - (seed.fresh ? 6 : 60 + index) * dayMs).toISOString(),
    popularity: seed.pop ?? 50,
    isNew: Boolean(seed.fresh),
  };
});

export const productById = new Map(products.map((p) => [p.id, p]));

