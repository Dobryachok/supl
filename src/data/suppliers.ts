import type { Supplier } from '@/types';

type Seed = Omit<Supplier, 'contacts'> & { contacts?: Partial<Supplier['contacts']> };

const translit = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-zа-я0-9]+/gi, '-')
    .replace(/^-|-$/g, '');

function build(seed: Seed): Supplier {
  const slug = translit(seed.name);
  return {
    ...seed,
    contacts: {
      phone: seed.contacts?.phone ?? '+7 (800) 550-41-83',
      email: seed.contacts?.email ?? `zakaz@${slug.replace(/-/g, '')}.ru`,
      site: seed.contacts?.site ?? `${slug.replace(/-/g, '')}.ru`,
      manager: seed.contacts?.manager ?? 'Отдел продаж',
    },
  };
}

